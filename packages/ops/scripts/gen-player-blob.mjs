// Bundle the playable page's script (player/player.ts: the Board demo as a
// player, plus the Storylet Engine runtime it imports) into ONE browser IIFE
// and inline it into an ops module, so runExportHtml can produce a single
// self-contained playable HTML file with no external <script src>. Patter's
// gen-runtime-blob.mjs, with the build folded in: our runtime has no minified
// browser artefact of its own, and the page needs the board UI as well as the
// engine, so one esbuild pass makes both from source. Commit the generated
// file; `npm run build` in ops re-runs this first (prebuild).
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const entry = resolve(here, "../player/player.ts");
const out = resolve(here, "../src/playable-player.ts");

// The root tsconfig's `paths` alias @storylet-studio/* to package SOURCE (the
// demo's own build does the same); anything not mapped, or mapped to a sibling
// checkout that is not there, falls through to node_modules.
const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: true,
  legalComments: "none",
  tsconfig: resolve(here, "../../../tsconfig.json"),
});
const js = result.outputFiles[0].text;
// The blob lands inside a <script> element verbatim; nothing in it may close one.
if (js.includes("</script")) throw new Error("the player bundle contains '</script'; it cannot be inlined");

const banner = "// GENERATED by scripts/gen-player-blob.mjs from player/player.ts (the Board demo as a player)\n" +
  "// and the @storylet-studio/runtime it imports, as one minified browser IIFE. Inlined by\n" +
  "// runExportHtml so a published page is a single self-contained HTML file.\n" +
  "// Do not edit by hand; re-run `node scripts/gen-player-blob.mjs` after a runtime or player change.\n";
writeFileSync(out, `${banner}export const PLAYABLE_PLAYER_JS = ${JSON.stringify(js)};\n`);
console.log(`wrote ${out} (${js.length} bytes of player)`);
